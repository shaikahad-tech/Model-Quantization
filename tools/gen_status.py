import hashlib
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]


def render(status):
    lines=['# Experiment status','',f"**{status['decision']}** — {status['release_status']}",'','Generated from status.json; do not edit this file by hand.','','| Work | Status | Evidence / blocker |','|---|---|---|']
    for name,row in status['work'].items():lines.append(f"| {name} | {row['status']} | {row['evidence']} |")
    body='\n'.join(lines)+'\n'
    return body+'\n<!-- generated_sha256: '+hashlib.sha256(body.encode()).hexdigest()+' -->\n'


if __name__=='__main__':(ROOT/'status.md').write_text(render(json.loads((ROOT/'status.json').read_text())))
