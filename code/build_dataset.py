"""Build v2 from licensed canonical source rows and recorded base-model replay."""
import argparse
import hashlib
import json
import random
import sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from common import ROOT,atomic_json,sha256
from experiment_data import BASE,REVISION,encode,jsonl,dedupe_report
from eval.scorers import refusal_v1

ALLOWED_LICENSES={'mit','apache-2.0','cc-by-4.0','cc-by-sa-3.0','cc-by-sa-4.0','cc0-1.0'}


def verify_sources(manifest):
    from huggingface_hub import HfApi
    result=[]
    for source in manifest['sources']:
        info=HfApi().dataset_info(source['id'],revision=source.get('revision'))
        card=dict(info.card_data or {});license=card.get('license')
        if info.gated or license not in ALLOWED_LICENSES:raise ValueError('Gated, unknown or disallowed license: '+source['id'])
        result.append({'id':source['id'],'revision':info.sha,'license':license,'card_sha256':hashlib.sha256(json.dumps(card,sort_keys=True).encode()).hexdigest()})
    return result


def build(input_dir,out,seed=20261111,max_len=512):
    from transformers import AutoTokenizer
    if out.exists() and any(p.name!='DATA_CARD.md' for p in out.iterdir()):raise FileExistsError('Never overwrite a dataset build')
    selection=json.loads((ROOT/'configs/task_selection.json').read_text())
    if selection.get('status')!='SELECTED':raise ValueError('Primary task must be selected before building v2')
    source_manifest=json.loads((input_dir/'sources.json').read_text());sources=verify_sources(source_manifest)
    primary=jsonl((input_dir/'primary_train.jsonl').read_bytes());replay=jsonl((input_dir/'base_replay.jsonl').read_bytes())
    accepted=[]
    for r in replay:
        if r.get('variant')!='base_fp16' or r.get('base_revision')!=REVISION:raise ValueError('Replay must be generated by pinned base_fp16')
        category=r.get('category')
        if category=='harmful' and not refusal_v1(r['generation']):raise ValueError('Unsafe replay answer must not enter training')
        if category=='benign_near_miss' and refusal_v1(r['generation']):raise ValueError('Over-refusal in benign replay')
        accepted.append(dict(r,instruction=r['prompt'],input='',output=r['generation']))
    if not {'harmful','benign_near_miss','dolly'}.issubset({r.get('category') for r in accepted}):raise ValueError('Replay requires Dolly, harmful refusal and benign near-miss cases')
    if len(primary)<980 or len(accepted)<420:raise ValueError('Need at least 980 primary and 420 replay rows for the 1,400-row recipe')
    rng=random.Random(seed);rng.shuffle(primary);rng.shuffle(accepted);train=primary[:980]+accepted[:420];rng.shuffle(train)
    tests={n:jsonl((input_dir/(n+'.jsonl')).read_bytes()) for n in ['val','test_primary','test_safety_harmful','test_safety_benign']}
    heldout=[r for rows in tests.values() for r in rows]
    report=dedupe_report(train,heldout)
    if report['exact_overlap'] or report['duplicate_rows'] or report['near_instruction_pairs']:raise ValueError('Train/test exact or near overlap; preserve and repair source split')
    tok=AutoTokenizer.from_pretrained(BASE,revision=REVISION)
    for row in train+heldout:
        if not row.get('category'):raise ValueError('Category must be retained')
        encode(tok,row,max_len=max_len)
    out.mkdir(parents=True,exist_ok=True)
    files={}
    for name,rows in dict(train=train,**tests).items():
        path=out/(name+'.jsonl');path.write_text(''.join(json.dumps(r,ensure_ascii=False)+'\n' for r in rows));files[name]={'count':len(rows),'sha256':sha256(path)}
    (out/'fixed_prompts.jsonl').write_bytes((ROOT/'data/fixed_prompts.jsonl').read_bytes())
    files['fixed_prompts']={'count':20,'sha256':sha256(out/'fixed_prompts.jsonl')}
    atomic_json(out/'manifest.json',{'seed':seed,'max_len':max_len,'truncation':False,'mixture':{'primary':980,'self_distilled_replay':420,'other_general':0},'sources':sources,'files':files,'overlap_report':report,'task_selection_sha256':sha256(ROOT/'configs/task_selection.json')})


def main():
    p=argparse.ArgumentParser();p.add_argument('--input-dir',type=Path,required=True);p.add_argument('--out',type=Path,required=True);p.add_argument('--seed',type=int,default=20261111);p.add_argument('--max-len',type=int,default=512);a=p.parse_args()
    build(a.input_dir,a.out,a.seed,a.max_len)


if __name__=='__main__':main()
